import { chromium } from 'playwright'
const B='https://movieflix.velixir.run'
const br=await chromium.launch({args:['--ignore-certificate-errors']})
const p=await (await br.newContext({viewport:{width:1280,height:1000}})).newPage()
await p.goto(B+'/baixar-app',{waitUntil:'networkidle',timeout:60000})
await p.waitForTimeout(1500)
await p.screenshot({path:'docs/apps-evidencias/prod-baixar-app.png',fullPage:true})
const t=await p.innerText('body')
console.log('TV mencionada:', /MovieFlix TV|Baixar para TV|Android TV/i.test(t))
console.log('Android:', /Baixar para Android/i.test(t))
console.log('iOS:', /Instalar no iPhone/i.test(t))
const a=await p.getAttribute('a[href="/apk/movieflix-android.apk"]','href').catch(()=>null)
console.log('link android:', a)
const ac=await (await br.newContext({viewport:{width:412,height:915},isMobile:true,hasTouch:true,userAgent:'Mozilla/5.0 (Linux; Android 14; Pixel 7) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120 Mobile Safari/537.36 MovieFlixApp/1.0'})).newPage()
await ac.goto(B+'/?app=android',{waitUntil:'networkidle',timeout:60000})
await ac.waitForTimeout(2000)
await ac.screenshot({path:'docs/apps-evidencias/prod-app-android.png'})
console.log('env:', await ac.getAttribute('html','data-mf-env'))
console.log('nav visivel:', await ac.isVisible('.nav'))
console.log('footer visivel:', await ac.isVisible('.footer'))
console.log('tabbar visivel:', await ac.isVisible('.mobile-nav'))
await br.close()
